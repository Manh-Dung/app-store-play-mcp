/**
 * Codegen — read the Google Play Android Publisher v3 Discovery Document
 * and emit generated TypeScript tool files in src/tools/generated/.
 *
 * Usage:
 *   npm run codegen
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  parseDiscoveryDoc,
  type DiscoveryDoc,
  type ParsedMethod,
  type DiscoveryParameter,
} from "../src/utils/discovery-parser.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SPEC_FILE = path.join(ROOT, "spec/androidpublisher-v3-discovery.json");
const OUT_DIR = path.join(ROOT, "src/tools/generated");

function zodTypeForParam(p: DiscoveryParameter): string {
  let expr: string;
  if (p.enum && p.enum.length > 0) {
    const enumLiterals = p.enum.map((e) => JSON.stringify(e)).join(", ");
    expr = `z.enum([${enumLiterals}])`;
  } else if (p.type === "integer") {
    expr = "z.coerce.number().int()";
  } else if (p.type === "number") {
    expr = "z.coerce.number()";
  } else if (p.type === "boolean") {
    expr = "z.boolean()";
  } else {
    expr = "z.string()";
  }

  if (p.description) {
    expr += `.describe(${JSON.stringify(p.description)})`;
  }
  if (!p.required) {
    expr += ".optional()";
  }
  return expr;
}

function generateToolCode(m: ParsedMethod): string {
  const paramLines = m.parameters.map((p) => `    ${JSON.stringify(p.name)}: ${zodTypeForParam(p)},`);
  if (m.hasRequestBody) {
    paramLines.push(
      `    requestBody: z.record(z.unknown()).optional().describe(${JSON.stringify(
        m.requestRef ? `Request body component: ${m.requestRef}` : "Request payload",
      )}),`,
    );
  }

  const inputBlock =
    paramLines.length > 0
      ? `z.object({\n${paramLines.join("\n")}\n  }).strict()`
      : "z.object({}).strict()";

  return `  defineTool({
    name: ${JSON.stringify(m.toolName)},
    description: ${JSON.stringify(m.description)},
    input: ${inputBlock},
    handler: async (args: any) => {
      const pub: any = await publisher();
      const res = await pub.${m.apiMethodPath}(args);
      return res.data;
    },
  }),`;
}

async function main(): Promise<void> {
  if (!fs.existsSync(SPEC_FILE)) {
    throw new Error(
      `Discovery doc not found at ${SPEC_FILE}. Run "npm run spec:download" first.`,
    );
  }

  process.stdout.write(`[codegen] Reading ${SPEC_FILE} …\n`);
  const raw = JSON.parse(fs.readFileSync(SPEC_FILE, "utf8")) as DiscoveryDoc;
  const methods = parseDiscoveryDoc(raw);
  process.stdout.write(`[codegen] Found ${methods.length} methods across resources.\n`);

  fs.mkdirSync(OUT_DIR, { recursive: true });

  // Group by top-level resource name
  const groups = new Map<string, ParsedMethod[]>();
  for (const m of methods) {
    const groupKey = m.resourcePath[0] ?? "general";
    if (!groups.has(groupKey)) {
      groups.set(groupKey, []);
    }
    groups.get(groupKey)!.push(m);
  }

  const fileExports: string[] = [];

  for (const [groupName, groupMethods] of groups) {
    const fileName = `${groupName}.ts`;
    const varName = `${groupName.replace(/_([a-z])/g, (_, c) => c.toUpperCase())}GeneratedTools`;

    const toolBlocks = groupMethods.map(generateToolCode).join("\n");

    const content = `// Auto-generated by scripts/codegen.ts from Google Play Discovery v3
// Resource: ${groupName} — Total tools: ${groupMethods.length}
// DO NOT EDIT BY HAND — re-run "npm run codegen" to regenerate.
/* eslint-disable */
import { z } from "zod";
import { defineTool, type Tool } from "../../utils/tool.js";
import { publisher } from "../../auth/client-factory.js";

export const ${varName}: Tool[] = [
${toolBlocks}
];
`;

    fs.writeFileSync(path.join(OUT_DIR, fileName), content, "utf8");
    fileExports.push(`export { ${varName} } from "./${groupName}.js";`);
  }

  // Generate index.ts
  const groupNames = Array.from(groups.keys());
  const indexContent = `// Auto-generated by scripts/codegen.ts
// DO NOT EDIT BY HAND
import type { Tool } from "../../utils/tool.js";
${groupNames
  .map(
    (g) =>
      `import { ${g.replace(/_([a-z])/g, (_, c) => c.toUpperCase())}GeneratedTools } from "./${g}.js";`,
  )
  .join("\n")}

${fileExports.join("\n")}

export const allGeneratedTools: Tool[] = [
${groupNames
  .map((g) => `  ...${g.replace(/_([a-z])/g, (_, c) => c.toUpperCase())}GeneratedTools,`)
  .join("\n")}
];
`;

  fs.writeFileSync(path.join(OUT_DIR, "index.ts"), indexContent, "utf8");
  process.stdout.write(
    `[codegen] Emitted ${groups.size} tool modules + index.ts (${methods.length} total tools) into ${OUT_DIR}\n`,
  );
}

main().catch((err) => {
  process.stderr.write(`[codegen] FATAL: ${(err as Error).stack ?? err}\n`);
  process.exit(1);
});
